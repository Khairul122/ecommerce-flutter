/// Core Design Tokens for spacing & padding scale across the application.
class AppSpacing {
  AppSpacing._();

  /// 4.0px - Very tight spacing (e.g. icon + tightly bound label)
  static const double xs = 4.0;

  /// 8.0px - Small spacing between related items in a group
  static const double sm = 8.0;

  /// 12.0px - Medium spacing (inside cards / inner padding)
  static const double md = 12.0;

  /// 16.0px - Large spacing (standard card margins / section elements)
  static const double lg = 16.0;

  /// 24.0px - Extra large spacing (page margins / main block separation)
  static const double xl = 24.0;

  /// 32.0px - Extra extra large spacing (hero section / top header margins)
  static const double xxl = 32.0;
}
